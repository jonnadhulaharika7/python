shopping_list = ["milk","eggs","bread","butter"]
print(shopping_list)

#Adding an item to the end of the list
shopping_list.append("vegetables")
print(shopping_list)

#Adding an item at a specific position
shopping_list.insert(2,"fruits")
print(shopping_list)

#Removing an item
shopping_list.remove("eggs")
print(shopping_list)

#Removing an item by index
shopping_list.pop(1)
print(shopping_list)

#Reversing the list
shopping_list.reverse()
print(shopping_list)

#Sorting the list
shopping_list.sort()
print(shopping_list)